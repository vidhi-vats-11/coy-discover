async function main() {
  // Clear existing demo data in dependency order.
  await prisma.match.deleteMany();
  await prisma.swipe.deleteMany();
  await prisma.profile.deleteMany();

  // Insert all 30 profiles.
  await prisma.profile.createMany({
    data: profiles,
  });

  const total = await prisma.profile.count();
  const likedYouCount = await prisma.profile.count({
    where: { likedYou: true },
  });

  console.log(`Successfully seeded ${total} profiles.`);
  console.log(`${likedYouCount} profiles have already liked you.`);
}

main()
  .catch((error) => {
    console.error("Seeding failed:", error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
